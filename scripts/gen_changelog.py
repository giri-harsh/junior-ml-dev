"""Generate CHANGELOG.md from git tags: one section per tag listing the commit subjects since the
previous tag (merge commits omitted). Tags are walked in creation order.

    uv run python scripts/gen_changelog.py [--notes TAG]   # --notes prints one section only
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout


def sections() -> list[tuple[str, str, list[str]]]:
    tags = git(
        "for-each-ref", "--sort=creatordate", "--format=%(refname:short)|%(objectname)", "refs/tags"
    ).split()
    out: list[tuple[str, str, list[str]]] = []
    prev = ""
    for line in tags:
        name, sha = line.split("|")
        rng = f"{prev}..{sha}" if prev else sha
        subjects = [
            s for s in git("log", "--no-merges", "--format=%s", rng).splitlines() if s.strip()
        ]
        date = git("log", "-1", "--format=%cs", sha).strip()
        out.append((name, date, subjects))
        prev = sha
    return out


def render(secs: list[tuple[str, str, list[str]]]) -> str:
    lines = ["# Changelog", "", "Generated by `scripts/gen_changelog.py` from git tags.", ""]
    for name, date, subjects in reversed(secs):
        lines += [f"## {name} ({date})", ""]
        lines += [f"- {s}" for s in subjects] or ["- (merge only)"]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--notes", default=None, help="print the section of one tag")
    a = ap.parse_args(argv)
    secs = sections()
    if a.notes:
        for name, date, subjects in secs:
            if name == a.notes:
                print(f"## {name} ({date})\n\n" + "\n".join(f"- {s}" for s in subjects))
                return 0
        return 1
    (ROOT / "CHANGELOG.md").write_text(render(secs), encoding="utf-8", newline="\n")
    print("wrote CHANGELOG.md with", len(secs), "tags")
    return 0


if __name__ == "__main__":
    sys.exit(main())
