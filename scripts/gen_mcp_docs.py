"""Generate docs/MCP_SERVERS.md from the live tool schemas of the four MCP servers.

uv run python scripts/gen_mcp_docs.py          # write
uv run python scripts/gen_mcp_docs.py --check  # exit 1 when the committed file is stale
"""

from __future__ import annotations

import argparse
import asyncio
import importlib
import json
import sys
from pathlib import Path
from typing import Any

SERVERS = [
    ("data-tools", "mcp_servers.data_tools.server"),
    ("sandbox-exec", "mcp_servers.sandbox_exec.server"),
    ("experiments", "mcp_servers.experiments.server"),
    ("deploy", "mcp_servers.deploy.server"),
]
OUT = Path(__file__).resolve().parents[1] / "docs" / "MCP_SERVERS.md"


def _fields(schema: dict[str, Any]) -> list[str]:
    """Flatten the single `request` argument (or plain properties) into 'name: type' lines."""
    defs = schema.get("$defs", {})
    props = schema.get("properties", {})
    if list(props) == ["request"]:
        ref = props["request"].get("$ref", "").rsplit("/", 1)[-1]
        inner = defs.get(ref, props["request"])
        props, required = inner.get("properties", {}), set(inner.get("required", []))
    else:
        required = set(schema.get("required", []))
    out = []
    for name, p in props.items():
        typ = p.get("type") or (
            "enum"
            if "enum" in p
            else "|".join(x.get("type", "?") for x in p.get("anyOf", [])) or "object"
        )
        extra = f", one of {p['enum']}" if "enum" in p else ""
        out.append(f"`{name}`: {typ}{extra}{'' if name in required else ' (optional)'}")
    return out


def render() -> str:
    lines = ["# MCP servers", "", "Generated by `scripts/gen_mcp_docs.py` from the live tool schemas; "
             "do not edit. Every server speaks MCP over stdio (`python -m <module>`).", ""]  # fmt: skip
    for name, module in SERVERS:
        mcp = importlib.import_module(module).mcp
        tools = asyncio.run(mcp.list_tools())
        lines += [
            f"## {name}",
            "",
            f"Module `{module}`. Instructions: {getattr(mcp, 'instructions', '') or '-'}",
            "",
        ]
        for t in sorted(tools, key=lambda x: x.name):
            lines += [f"### `{t.name}`", "", (t.description or "").strip(), ""]
            lines += [f"- {f}" for f in _fields(t.input_schema)] or ["- (no arguments)"]
            lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print("up to date" if ok else "STALE: run scripts/gen_mcp_docs.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT, json.dumps({"servers": len(SERVERS)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
