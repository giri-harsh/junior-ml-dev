"""Render docs/METRICS.md: every headline number with the file (or CI run) it comes from.

Only numbers present in benchmarks/results/*.json (or in ci_evidence.json, written by
scripts/collect_ci_evidence.py from the GitHub API) are used. Percentiles of per-task latency are
computed here from the per-task values stored in the agent result files.

    uv run python scripts/render_metrics.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "benchmarks" / "results"


def load(name: str) -> dict[str, Any] | None:
    p = RES / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def ci(v: list[float] | None) -> str:
    return "n/a" if not v else f"{v[0]:.3f} [{v[1]:.3f}, {v[2]:.3f}]"


def src(name: str) -> str:
    return f"[`{name}.json`](../benchmarks/results/{name}.json)"


def agent_rows(lines: list[str], name: str, label: str) -> None:
    d = load(name)
    if d is None:
        lines.append(f"| {label} | NOT RUN | | | {src(name)} |")
        return
    r = d["results"]
    a = r["aggregate"]
    pt = r["per_task"].values()
    lat = [t["latency_s"] for t in pt]
    tokens = sum(t.get("llm_tokens", 0) for t in pt)
    req = sum(t.get("llm_requests", 0) for t in pt)
    w = a["pass_vs_linear"]["wilson95"]
    lines.append(
        f"| {label} | {ci(a.get('agent_normalized_mean_ci95'))} | "
        f"vs linear {ci(a.get('agent_minus_linear_paired_ci95'))}; "
        f"vs FLAML {ci(a.get('agent_minus_flaml_paired_ci95'))} | "
        f"{a['pass_vs_linear']['k']}/{a['pass_vs_linear']['n']} (Wilson {w[0]:.2f}-{w[1]:.2f}) | "
        f"latency p50 {np.percentile(lat, 50):.0f}s / p95 {np.percentile(lat, 95):.0f}s per task; "
        f"{req} LLM requests, {tokens} tokens, $0 | {src(name)} |"
    )


def main() -> int:
    L = ["# Verified metrics", "", "Generated by `scripts/render_metrics.py`. Each row names its "
         "source file or CI run. Planner and LLM mode are stated in every agent row.", ""]  # fmt: skip
    L += ["## Agent benchmark v5 (headline; unseen partition, each arm run once)", "",
          "| Arm | Normalized score [95% CI] | Paired differences | Pass vs linear | Cost / latency | Source |",
          "|---|---|---|---|---|---|"]  # fmt: skip
    agent_rows(L, "agent_v5_scripted", "SCRIPTED planner (no LLM)")
    agent_rows(L, "agent_v5_llm", "REAL-LLM planner v2")
    b = load("baselines_v5")
    if b:
        ag = b["results"]["aggregate"]
        L += ["", f"Linear baseline normalized mean {ci(ag.get('normalized_linear_ci95') and [ag['normalized_linear_mean'], *ag['normalized_linear_ci95']])} "
              f"(n={ag['normalized_linear_defined_n']}); FLAML = 1 by definition. Source: {src('baselines_v5')}."]  # fmt: skip
    d = load("agent_v5_llm")
    s = load("agent_v5_scripted")
    if d and s:
        pr = d["results"]["aggregate"].get("paired_vs_prior_ci95")
        if pr:
            L += [
                f"Paired LLM minus scripted: {ci(pr)} (n={d['results']['aggregate']['paired_vs_prior_n']})."
            ]
    L += ["", "## Leakage detector", ""]
    lk = load("leakage_v3")
    if lk:
        sm = lk["results"]["eval4"]["summary"]
        L += [f"- eval4 (unseen planted partition, {sm['n_variants']} variants): recall {sm['overall_recall']:.3f} "
              f"(bootstrap 95% {sm['overall_recall_bootstrap95']}), clean-twin false alarms {sm['twin_fpr']:.3f} "
              f"(Wilson 95% {sm['twin_fpr_wilson95']}). Source: {src('leakage_v3')}."]  # fmt: skip
    L += ["", "## Injection defence", ""]
    inj = load("injection_llm_v2") or load("injection_llm_v1")
    name = "injection_llm_v2" if load("injection_llm_v2") else "injection_llm_v1"
    if inj:
        r = inj["results"]
        L += [f"- Real LLM in the loop ({name}): attacker action proposed {r['all']['behaviour_change']}/{r['all']['n']}, "
              f"unsafe actions executed {r['all']['unsafe_executed']}/{r['all']['n']}. Source: {src(name)}."]  # fmt: skip
    cv = load("critic_v5")
    cc = load("critic_calibration")
    L += ["", "## Critic (advisory)", ""]
    if cv:
        r = cv["results"]
        L += [f"- v5 runs, critic v2 vs rule reviewer: agreement {r['agree']}/{r['n_valid']} "
              f"(Wilson 95% {r['agreement_wilson95'][0]:.2f}-{r['agreement_wilson95'][1]:.2f}); "
              f"confusion {r['confusion']}; {r['requests']} requests. Source: {src('critic_v5')}."]  # fmt: skip
    else:
        L += ["- v5 critic agreement: NOT RUN."]
    if cc:
        L += [f"- Dev calibration (mutated states): see {src('critic_calibration')}."]
    L += ["", "## Infrastructure (GitHub Actions evidence)", ""]
    ev = load("ci_evidence")
    if ev:
        e = ev["results"]
        L += [f"- {k}: {v}" for k, v in e.items()]
    else:
        L += ["- NOT COLLECTED (run scripts/collect_ci_evidence.py)."]
    L += ["", "## Load test", ""]
    ld = load("load_v1")
    if ld:
        L += [
            "| Users | RPS | p50 ms | p95 ms | p99 ms | error rate |",
            "|---|---|---|---|---|---|",
        ]
        for users, v in sorted(ld["results"]["concurrency"].items(), key=lambda kv: int(kv[0])):
            a = v["aggregate"]
            L.append(
                f"| {users} | {a['rps']:.1f} | {a['p50_ms']:.0f} | {a['p95_ms']:.0f} | {a['p99_ms']:.0f} | {a['error_rate']:.3f} |"
            )
        L += ["", f"Source: {src('load_v1')} (CI run {ld['results'].get('ci_run_id')}); hosted-runner numbers, not a capacity claim."]  # fmt: skip
    else:
        L += ["NOT RUN."]
    (ROOT / "docs" / "METRICS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/METRICS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
