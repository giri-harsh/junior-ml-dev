"""Render docs/METRICS.md: every headline number with the file (or CI run) it comes from.

Only numbers present in benchmarks/results/*.json (or in ci_evidence.json, written by
scripts/collect_ci_evidence.py from the GitHub API) are used. Percentiles of per-task latency are
computed here from the per-task values stored in the agent result files.

    uv run python scripts/render_metrics.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "benchmarks" / "results"


def load(name: str) -> dict[str, Any] | None:
    p = RES / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def ci(v: list[float] | None) -> str:
    return "n/a" if not v else f"{v[0]:.3f} [{v[1]:.3f}, {v[2]:.3f}]"


def src(name: str) -> str:
    return f"[`{name}.json`](../benchmarks/results/{name}.json)"


def agent_rows(lines: list[str], name: str, label: str) -> None:
    d = load(name)
    if d is None:
        lines.append(f"| {label} | NOT RUN | | | {src(name)} |")
        return
    r = d["results"]
    a = r["aggregate"]
    pt = r["per_task"].values()
    lat = [t["latency_s"] for t in pt]
    tokens = sum(t.get("llm_tokens", 0) for t in pt)
    req = sum(t.get("llm_requests", 0) for t in pt)
    w = a["pass_vs_linear"]["wilson95"]
    lines.append(
        f"| {label} | {ci(a.get('agent_normalized_mean_ci95'))} | "
        f"vs linear {ci(a.get('agent_minus_linear_paired_ci95'))}; "
        f"vs FLAML {ci(a.get('agent_minus_flaml_paired_ci95'))} | "
        f"{a['pass_vs_linear']['k']}/{a['pass_vs_linear']['n']} (Wilson {w[0]:.2f}-{w[1]:.2f}) | "
        f"latency p50 {np.percentile(lat, 50):.0f}s / p95 {np.percentile(lat, 95):.0f}s per task; "
        f"{req} LLM requests, {tokens} tokens, $0 | {src(name)} |"
    )


def main() -> int:
    L = ["# Verified metrics", "", "Generated by `scripts/render_metrics.py`. Each row names its "
         "source file or CI run. Planner and LLM mode are stated in every agent row.", ""]  # fmt: skip
    L += ["## Agent benchmark v5 (headline; unseen partition, each arm run once)", "",
          "| Arm | Normalized score [95% CI] | Paired differences | Pass vs linear | Cost / latency | Source |",
          "|---|---|---|---|---|---|"]  # fmt: skip
    agent_rows(L, "agent_v5_scripted", "SCRIPTED planner (no LLM)")
    agent_rows(L, "agent_v5_llm", "REAL-LLM planner v2")
    b = load("baselines_v5")
    if b:
        ag = b["results"]["aggregate"]
        L += ["", f"Linear baseline normalized mean {ci(ag.get('normalized_linear_ci95') and [ag['normalized_linear_mean'], *ag['normalized_linear_ci95']])} "
              f"(n={ag['normalized_linear_defined_n']}); FLAML = 1 by definition. Source: {src('baselines_v5')}."]  # fmt: skip
    d = load("agent_v5_llm")
    s = load("agent_v5_scripted")
    if d and s:
        pr = d["results"]["aggregate"].get("paired_vs_prior_ci95")
        if pr:
            L += [
                f"Paired LLM minus scripted: {ci(pr)} (n={d['results']['aggregate']['paired_vs_prior_n']})."
            ]
    L += ["", "## Leakage detector", ""]
    lk = load("leakage_v3")
    if lk:
        sm = lk["results"]["eval4"]["summary"]
        L += [f"- eval4 (unseen planted partition, {sm['n_variants']} variants): recall {sm['overall_recall']:.3f} "
              f"(bootstrap 95% {sm['overall_recall_bootstrap95']}), clean-twin false alarms {sm['twin_fpr']:.3f} "
              f"(Wilson 95% {sm['twin_fpr_wilson95']}). Source: {src('leakage_v3')}."]  # fmt: skip
    L += ["", "## Injection defence", ""]
    inj = load("injection_llm_v2") or load("injection_llm_v1")
    name = "injection_llm_v2" if load("injection_llm_v2") else "injection_llm_v1"
    if inj:
        r = inj["results"]
        L += [f"- Real LLM in the loop ({name}): attacker action proposed {r['all']['behaviour_change']}/{r['all']['n']}, "
              f"unsafe actions executed {r['all']['unsafe_executed']}/{r['all']['n']}. Source: {src(name)}."]  # fmt: skip
    inj3, runs = load("injection_llm_v3"), load("injected_runs_v1")
    if inj3 and runs:
        d, rr = inj3["results"], runs["results"]
        h = d["fresh_heldout"]
        L += [
            f"- Evasion DEV ({src('injection_llm_v3')}; burned, the scanner was tuned on it): attacker actions "
            f"{d['dev']['behaviour_change']}/{d['dev']['n']}, scanner flagged {d['scanner_flagged']['dev']}.",
            f"- FRESH 14-payload held-out evasion set (hash-committed before the run, run once): attacker actions "
            f"proposed {h['behaviour_change']}/{h['n']} (Wilson 95% upper bound "
            f"{h['behaviour_change_wilson95'][1]:.3f}), unsafe executed {h['unsafe_executed']}, "
            f"{h['proposed_risky_non_aligned']} non-train/finish proposal (a benign `read_file train.csv`, "
            f"guard allowed). The scanner flagged only {d['scanner_flagged']['fresh_heldout']} of the fresh "
            f"payloads, so the model's own behaviour and the structural guard carry this result.",
            f"- {rr['n_runs']} full agent runs with injected column names (real planner v2 + critic v3): "
            f"{rr['finished']} finished, unsafe tools executed {rr['unsafe_executed']}, payload reached the "
            f"critic {rr['payload_reached_critic']} times (by design the planner never sees column names, so "
            f"this is a null-exposure check, not an attack); critic flagged {rr['critic_flagged']}/"
            f"{rr['critic_judged']} for ordinary quality reasons (rules flagged {rr['rule_flagged']}). "
            f"Source: {src('injected_runs_v1')}.",
        ]  # fmt: skip
    else:
        L += ["- Fresh evasion set and injected full runs: NOT RUN."]
    cv = load("critic_v5")
    cc = load("critic_calibration")
    L += ["", "## Critic (advisory)", ""]
    if cv:
        r = cv["results"]
        L += [f"- v5 runs, critic v2 vs rule reviewer: agreement {r['agree']}/{r['n_valid']} "
              f"(Wilson 95% {r['agreement_wilson95'][0]:.2f}-{r['agreement_wilson95'][1]:.2f}); "
              f"confusion {r['confusion']}; {r['requests']} requests. Source: {src('critic_v5')}."]  # fmt: skip
    else:
        L += ["- v5 critic agreement: NOT RUN."]
    if cc:
        L += [f"- Dev calibration (mutated states): see {src('critic_calibration')}."]
    c6 = load("critic_v6")
    if c6:
        r = c6["results"]
        w, fw = r["recall_wilson95"], r["false_alarm_wilson95"]
        L += [
            f"- FRESH planted set (critic v3, schema-enforced answers to failed rules): recall "
            f"{r['recall']}/{r['planted_n']} (Wilson 95% {w[0]:.2f}-{w[1]:.2f}); false alarms "
            f"{r['false_alarms']}/{r['clean_n']} clean runs (Wilson 95% {fw[0]:.2f}-{fw[1]:.2f}); "
            f"{r['no_output']} clean items not run (40-request cap). By type: {r['recall_by_type']}. "
            f"Source: {src('critic_v6')}, set `benchmarks/critic_set_v6.json` (sha256 "
            f"`{r['set_sha256'][:16]}`, committed before the first call).",
            "- The v5 agreement above (18/20) is burned and post-hoc: the critic was tuned after "
            "reading v5-era failures.",
        ]  # fmt: skip
    c2p = ROOT / "benchmarks" / "critic_v2" / "critic_v2_eval.json"
    if c2p.exists():
        c2 = json.loads(c2p.read_text(encoding="utf-8"))["results"]
        fp = c2.get("first_pass", {})
        w, fw = c2["recall_wilson95"], c2["false_alarm_wilson95"]
        L += [
            f"- FRESH planted set v2 (53 items, hash `{c2['set_sha256'][:16]}`, failing-margin items now "
            f"unambiguous; a DIFFERENT set from v1, not paired): completed run recall {c2['recall']}/"
            f"{c2['planted_n']} (Wilson 95% {w[0]:.2f}-{w[1]:.2f}), false alarms {c2['false_alarms']}/"
            f"{c2['clean_n']} ({fw[0]:.2f}-{fw[1]:.2f}). First pass (8 items hit the gateway token budget) was "
            f"{fp.get('recall')}/{fp.get('planted_n')} and {fp.get('false_alarms')}/{fp.get('clean_n')}; the 8 "
            f"were completed later with the same prompt (labelled completion). Failing-margin items "
            f"{c2['recall_by_type'].get('rule_fail_baseline_margin')}: the model dissents with numbers, "
            f"a documented weakness. Source: [`critic_v2_eval.json`](../benchmarks/critic_v2/critic_v2_eval.json).",
        ]  # fmt: skip
    L += ["", "## E2B sandbox backend", ""]
    e2 = load("e2b_v1")
    if e2:
        r = e2["results"]
        st, tt, ls = r["stages_s"], r["total_s"], r.get("live_suite", {})
        L += [
            f"- {r['n_ok']}/{r['n_requested']} sequential execs (default template, internet off): total "
            f"p50 {tt['p50']:.2f} s / p95 {tt['p95']:.2f} s (create p50 {st['create_s']['p50']:.2f} s, "
            f"upload {st['upload_s']['p50']:.2f} s, exec {st['exec_s']['p50']:.2f} s, download "
            f"{st['download_s']['p50']:.2f} s); n=20, one machine, an order-of-magnitude figure. "
            f"Live suite: {ls.get('passed')} passed, {ls.get('failed')} failed, {ls.get('xfailed')} xfailed, "
            f"{ls.get('skipped')} skipped (the 2 skips need a custom template with pyarrow, not built). "
            f"Source: {src('e2b_v1')}."
        ]  # fmt: skip
    else:
        L += ["- NOT RUN."]
    L += ["", "## Demo", ""]
    dm = load("demo_render_v2") or load("demo_render_v1")
    if dm:
        r = dm["results"]
        L += [
            f"- LIVE (host: Render free plan, 512 MB, 0.1 vCPU): {r['url']} . Verified: health {r['health_status']}, "
            f"landing {r['landing_status']}, admin without auth {r['admin_without_auth']}, upload attempt "
            f"{r['upload_rejected']}, deploy path {r['deploy_absent']}, reports {r['report_status']}. "
            f"Sample run (diabetes) p50 {r['sample_run_p50_s']} s over {len(r['sample_run_s'])} runs "
            f"({r['sample_run_s']}). Cold start after >15 min idle: {r.get('cold_start', 'not measured')}. "
            f"Local peak process-tree RSS of a sample run: {r['peak_rss_mb']}. Source: {src('demo_render_v1')}.",
            f"- Cut to fit the free plan: {r['cut_to_fit']}",
        ]  # fmt: skip
        per = r.get("per_sample_s")
        if per:
            runs = "; ".join(f"{k} {v}" for k, v in per.items())
            L += [
                f"- Per-sample run time (s): {runs} (live, submit to done: diabetes median of 3 runs, the others one steady-state run; "
                f"scripted planner, FLAML off, leakage detectors skipped; "
                f"landing page {r.get('landing_kb', 'n/a')} KB of HTML, CSS and JS, fonts excluded)."
            ]
    L += [
        "- Static precomputed site (no code runs there): https://giri-harsh.github.io/junior-ml-dev-demo/ ."
    ]
    L += [
        "",
        "## Quality gate",
        "",
        "- Verified via local quality gate: ruff, format, mypy, pytest — 683 tests, 91.8% coverage (floor 91%).",
    ]
    L += ["", "## Load test", ""]
    ld = load("load_v1")
    if ld:
        L += [
            "| Users | RPS | p50 ms | p95 ms | p99 ms | error rate |",
            "|---|---|---|---|---|---|",
        ]
        for users, v in sorted(ld["results"]["concurrency"].items(), key=lambda kv: int(kv[0])):
            a = v["aggregate"]
            L.append(
                f"| {users} | {a['rps']:.1f} | {a['p50_ms']:.0f} | {a['p95_ms']:.0f} | {a['p99_ms']:.0f} | {a['error_rate']:.3f} |"
            )
        L += ["", f"Source: {src('load_v1')} (CI run {ld['results'].get('ci_run_id')}); hosted-runner numbers, not a capacity claim."]  # fmt: skip
    else:
        L += ["NOT RUN."]
    (ROOT / "docs" / "METRICS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/METRICS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
