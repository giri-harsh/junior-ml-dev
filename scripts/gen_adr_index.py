"""Generate docs/adr/README.md (an index of the ADRs) from the ADR files' titles.

uv run python scripts/gen_adr_index.py [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ADR = Path(__file__).resolve().parents[1] / "docs" / "adr"


def render() -> str:
    rows = []
    for p in sorted(ADR.glob("[0-9][0-9][0-9]-*.md")):
        first = p.read_text(encoding="utf-8").splitlines()[0]
        title = re.sub(r"^#\s*(ADR-\d+:?\s*)?", "", first).strip()
        rows.append(f"| [{p.stem.split('-')[0]}]({p.name}) | {title} |")
    head = [
        "# Architecture decision records",
        "",
        "Generated by `scripts/gen_adr_index.py`. Numbered one-line decisions that do not need a",
        "full ADR are in [../DECISIONS.md](../DECISIONS.md).",
        "",
        "| ADR | Title |",
        "|---|---|",
    ]
    return "\n".join([*head, *rows]) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    out = ADR / "README.md"
    text = render()
    if a.check:
        ok = out.exists() and out.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print("up to date" if ok else "STALE: run scripts/gen_adr_index.py")
        return 0 if ok else 1
    out.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
