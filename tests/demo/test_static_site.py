def make_cache(tmp: Path, keys: tuple[str, ...] = ("diabetes", "credit-g", "wine-quality")) -> Path:
    cache = tmp / "cache"
    recs = []
    for i, key in enumerate(keys):
        (cache / key).mkdir(parents=True)
        (cache / key / "report.html").write_text(
            f"<html><body><h1>Run on {key}: planner=scripted</h1></body></html>", encoding="utf-8"
        )
        recs.append(
            asdict(
                RunRecord(
                    key=key,
                    title=f"Title {key}",
                    blurb="blurb <b>x</b>",
                    openml_id=37 + i,
                    task_type="binary" if i < 2 else "regression",
                    metric="roc_auc" if i < 2 else "rmse",
                    rows=100,
                    cols=5,
                    run_id=f"demo-{i}",
                    status="done",
                    wall_s=40.5,
                    summary={
                        "status": "done",
                        "chosen_family": "linear",
                        "val_score": 0.8,
                        "review": "APPROVE",
                        "n_steps": 2,
                        "latency_s": 38.2,
                        "dropped": [],
                    },
                    steps=[
                        {
                            "idx": 0,
                            "tool": "profile_dataset",
                            "server": "data-tools",
                            "ok": True,
                            "latency_s": 0.4,
                        },
                        {
                            "idx": 1,
                            "tool": "train_model",
                            "server": "experiments",
                            "ok": True,
                            "latency_s": 1.5,
                        },
                    ],
                    budget={"max_wall_s": 55, "flaml_budget_s": 15, "tune_trials": 3},
                    ran_at="2026-11-09 11:00 UTC",
                )
            )
        )
    (cache / "runs.json").write_text(json.dumps(recs), encoding="utf-8")
    return cache


