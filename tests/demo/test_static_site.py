def test_the_committed_site_is_clean_and_complete() -> None:
    site = REPO / "site"
    files = dst.check_site(site, {})
    for need in ("index.html", "results.html", "architecture.html", ".nojekyll"):
        assert need in files
    runs = {f.split("/")[1] for f in files if f.startswith("runs/")}
    assert runs == {"diabetes", "credit-g", "wine-quality"}
    # not compared with the current METRICS.md (which other work may regenerate): the page shows
    # the figures it was built from, with the file hash on the home page
    results = (site / "results.html").read_text(encoding="utf-8")
    assert len(re.findall(r"\d\.\d{3} \[[^\]]+\]", results)) >= 2
    assert re.search(
        r"file hash\s*<code>[0-9a-f]{12}</code>", (site / "index.html").read_text(encoding="utf-8")
    )
    assert not [f for f in files if f.endswith(".py")]
