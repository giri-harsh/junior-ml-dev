def serve(site: Path, base: str = "https://example.test/demo/", drop: set[str] | None = None,
          tamper: str | None = None) -> httpx.Client:  # fmt: skip
    def handler(request: httpx.Request) -> httpx.Response:
        rel = request.url.path.removeprefix("/demo/")
        p = site / rel
        if rel in (drop or set()) or not p.is_file():
            return httpx.Response(404, text="nope")
        body = p.read_bytes()
        if rel == tamper:
            body += b"<!-- changed -->"
        return httpx.Response(200, content=body, headers={"content-type": "text/html"})

    return httpx.Client(transport=httpx.MockTransport(handler))


def test_verify_passes_for_a_faithful_deployment_and_measures_latency(site: Path) -> None:
    rep = dst.verify_site(serve(site), "https://example.test/demo/", site, repeats=3)
    assert rep.ok, dst.format_site_report(rep)
    j = rep.to_json()
    assert j["pages_fetched"] > 15 and j["latency_ms_p50"] is not None
    assert "ALL CHECKS PASSED" in dst.format_site_report(rep)


def test_verify_fails_on_a_missing_page_a_changed_page_and_a_broken_link(site: Path) -> None:
    missing = dst.verify_site(
        serve(site, drop={"runs/credit-g/report.html"}), "https://example.test/demo/", site
    )
    assert not missing.ok and any("every built page" in c.name and not c.ok for c in missing.checks)
    changed = dst.verify_site(
        serve(site, tamper="results.html"), "https://example.test/demo/", site
    )
    assert any("equal the built site" in c.name and not c.ok for c in changed.checks)
    (site / "index.html").write_text(
        (site / "index.html").read_text(encoding="utf-8") + '<a href="gone.html">x</a>',
        encoding="utf-8",
    )
    broken = dst.verify_site(serve(site), "https://example.test/demo/", site)
    assert any("broken internal links" in c.name and not c.ok for c in broken.checks)


def test_wait_for_url_polls_until_200_and_gives_up() -> None:
    class Seq:
        def __init__(self, codes: list[int]) -> None:
            self.codes = codes

        def get(self, url: str) -> httpx.Response:
            c = self.codes.pop(0) if len(self.codes) > 1 else self.codes[0]
            if c == 0:
                raise ConnectionError("down")
            return httpx.Response(c)

    sleeps: list[float] = []
    assert dst.wait_for_url(Seq([404, 0, 200]), "u", attempts=5, sleep=sleeps.append) == (True, 3)
    assert len(sleeps) == 2
    assert dst.wait_for_url(Seq([404]), "u", attempts=3, sleep=lambda s: None) == (False, 3)


