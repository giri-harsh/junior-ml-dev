"""Deterministic markdown narrative from a profile and leakage findings (no LLM)."""

from __future__ import annotations

from datastory.models import DatasetProfile, StoryResult
from leakage.models import Finding, Severity


def _fmt_pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def build_markdown(profile: DatasetProfile, findings: list[Finding]) -> str:
    lines = ["# Data Story", ""]
    lines.append(
        f"The dataset has **{profile.n_rows:,} rows** and **{profile.n_cols} columns**"
        f" ({profile.duplicate_rows:,} fully duplicated rows)."
    )
    if profile.sample and profile.sample.sampled:
        lines.append(
            f"_Analysis used a seeded sample of {profile.sample.n_used:,} of"
            f" {profile.sample.n_full:,} rows (seed {profile.sample.seed})._"
        )
    t = profile.target
    if t:
        lines += ["", "## Target"]
        if t.task_type == "regression":
            lines.append(f"`{t.name}` is a numeric target (skew {t.skew}).")
        else:
            lines.append(
                f"`{t.name}` has {t.n_classes} classes; the majority class is"
                f" {_fmt_pct(t.majority_fraction or 0)} of rows"
                f" (imbalance ratio {t.imbalance_ratio}:1)."
            )
        if t.missing_frac > 0:
            lines.append(f"{_fmt_pct(t.missing_frac)} of target values are missing.")
    lines += ["", "## Data quality"]
    quality = [
        ("Constant columns", profile.constant_columns),
        ("Near-constant columns (>=99% one value)", profile.near_constant_columns),
        ("Columns with >=30% missing", profile.high_missing_columns),
        ("High-cardinality categoricals", profile.high_cardinality_columns),
    ]
    any_q = False
    for label, cols in quality:
        if cols:
            any_q = True
            lines.append(f"- {label}: {', '.join(f'`{c}`' for c in cols[:10])}")
    if not any_q:
        lines.append(
            "- No constant, near-constant, high-missing or high-cardinality columns found."
        )
    lines += ["", "## Suspected roles"]
    roles = [
        ("ID-like", profile.suspected_id),
        ("Time-like", profile.suspected_time),
        ("Group-like", profile.suspected_group),
    ]
    for label, cols in roles:
        lines.append(f"- {label}: {', '.join(f'`{c}`' for c in cols) if cols else 'none'}")
    ranked = sorted(
        (c for c in profile.columns if c.target_association),
        key=lambda c: (-(c.target_association or 0), c.name),
    )[:5]
    if ranked:
        lines += ["", "## Strongest associations with the target"]
        for c in ranked:
            lines.append(f"- `{c.name}`: {c.target_association} ({c.association_method})")
    lines += ["", "## Leakage review"]
    flagged = [f for f in findings if f.severity != Severity.LOW]
    if not flagged:
        lines.append("No medium or high severity leakage findings.")
    for f in flagged:
        where = ", ".join(f"`{c}`" for c in f.columns) or "dataset-level"
        lines.append(
            f"- **{f.severity.value.upper()}** `{f.type.value}` on {where}"
            f" (confidence {f.confidence:.2f}): {f.evidence}"
        )
    advisory = [f for f in findings if f.severity == Severity.LOW]
    if advisory:
        lines.append(
            f"- Advisory: {len(advisory)} low-severity note(s), e.g. ID-like columns to drop."
        )
    lines += ["", "_Generated by deterministic code; every number comes from the profile above._"]
    return "\n".join(lines) + "\n"


def build_story(
    profile: DatasetProfile, findings: list[Finding], meta: dict[str, object] | None = None
) -> StoryResult:
    return StoryResult(
        profile=profile,
        findings=findings,
        markdown=build_markdown(profile, findings),
        meta=meta or {},
    )
